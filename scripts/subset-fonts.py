"""Subsets the site's Latin fonts to what the site needs and writes
src/styles/fonts.css. Each face stays in two halves (basic Latin, Latin
Extended), as the variable sources come split; each half keeps only:
Latin-1, Latin Extended-A (Turkish, long vowels), the transliteration letters
with dots and lines below, ʿ ʾ, common punctuation, and every character found
in the built pages. Run after `npx astro build`:
    python3 scripts/subset-fonts.py
Outputs are committed, so the site build itself never needs Python."""
import glob, html, os, re, subprocess, sys
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NM = os.path.join(ROOT, 'node_modules')
OUT = os.path.join(ROOT, 'src/styles/fonts')

chars = set(range(0x20, 0x7F)) | set(range(0xA0, 0x180))
chars |= {ord(c) for c in 'ḤḥṢṣḌḍṬṭẒẓḎḏṮṯĠġʿʾ‘’“”–—…·•→←×±−′″€'}
for f in glob.glob(os.path.join(ROOT, 'dist/**/*.html'), recursive=True):
    text = html.unescape(re.sub(r'<[^>]+>', ' ', open(f, encoding='utf8').read()))
    chars |= {ord(c) for c in text if ord(c) < 0x0590 or 0x1E00 <= ord(c) <= 0x2BFF}

# family, style, weight range, source pattern ({s} = latin | latin-ext)
FACES = [
    ('Fraunces Variable', 'normal', '100 900', 'fraunces', '@fontsource-variable/fraunces/files/fraunces-{s}-soft-normal.woff2'),
    ('Fraunces Variable', 'italic', '100 900', 'fraunces-italic', '@fontsource-variable/fraunces/files/fraunces-{s}-soft-italic.woff2'),
    ('Literata Variable', 'normal', '200 900', 'literata', '@fontsource-variable/literata/files/literata-{s}-wght-normal.woff2'),
    ('Literata Variable', 'italic', '200 900', 'literata-italic', '@fontsource-variable/literata/files/literata-{s}-wght-italic.woff2'),
    ('Inter Variable', 'normal', '100 900', 'inter', '@fontsource-variable/inter/files/inter-{s}-wght-normal.woff2'),
    ('IBM Plex Mono', 'normal', '400', 'plex-mono', '@fontsource/ibm-plex-mono/files/ibm-plex-mono-{s}-400-normal.woff2'),
]

def ranges(cps):
    cps = sorted(cps); out = []; start = prev = cps[0]
    for c in cps[1:]:
        if c != prev + 1:
            out.append((start, prev)); start = c
        prev = c
    out.append((start, prev))
    return ','.join(f'U+{a:04X}' if a == b else f'U+{a:04X}-{b:04X}' for a, b in out)

css = ['/* Generated by scripts/subset-fonts.py: subsetted Latin faces.\n   Combining marks are left out of every unicode-range on purpose: when two\n   faces claim U+0304, Chromium builds ā from the wrong pieces (see git log). */\n']
claimed = set()
for family, style, weight, name, pat in FACES:
    for half, sub in (('a', 'latin'), ('b', 'latin-ext')):
        src = os.path.join(NM, pat.format(s=sub))
        cmap = set(TTFont(src).getBestCmap())
        need = {c for c in chars & cmap if not 0x0300 <= c <= 0x036F}
        if half == 'b':
            need -= claimed_a  # a code point belongs to one half only
        out = f'{name}-{half}.woff2'
        subprocess.run([sys.executable, '-m', 'fontTools.subset', src, '--unicodes=' + ranges(need),
                        '--flavor=woff2', '--layout-features=*', '--output-file=' + os.path.join(OUT, out)], check=True)
        if half == 'a':
            claimed_a = need
        css.append(f"@font-face {{\n  font-family: '{family}';\n  font-style: {style};\n  font-weight: {weight};\n"
                   f"  font-display: swap;\n  src: url('./fonts/{out}') format('woff2');\n  unicode-range: {ranges(need)};\n}}\n")
open(os.path.join(ROOT, 'src/styles/fonts.css'), 'w').write('\n'.join(css))
print(len(chars), 'characters')
