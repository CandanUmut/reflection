// Writes dist/sw.js after each build: the service worker that lets the site be
// installed and read offline.
// - Precached on install: the home pages, the section lists, the garden, the
//   offline page, and every script, stylesheet and font those pages use.
// - Every other page is saved the first time it is opened, so anything read
//   once can be read again offline.
// - Pages: network first (always the latest when online), the saved copy when
//   offline, the offline page when it was never saved.
// - Scripts and fonts (_astro/): cache first; their names change when they do.
// - Icons and the manifest: network first, saved copy offline.
// Three caches: the shell (replaced with each build), pages the reader opened,
// and assets. Pages and assets survive updates, so what was read stays readable
// offline; asset names are hashed, so old pages keep finding their own files.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const SHELL = [
  '',
  'offline/',
  'tr/',
  'tr/tefekkur/',
  'tr/yasam/',
  'tr/sor/',
  'tr/bahce/',
  'en/',
  'en/reflect/',
  'en/live/',
  'en/ask/',
  'en/garden/',
];
const STATIC = ['manifest.webmanifest', 'favicon.svg', 'logo.svg', 'icons/icon-192.png', 'icons/icon-512.png'];

export default function pwa() {
  let base = '/';
  return {
    name: 'tefekkur-pwa',
    hooks: {
      'astro:config:done': ({ config }) => {
        base = config.base.replace(/\/?$/, '/');
      },
      'astro:build:done': ({ dir }) => {
        const out = fileURLToPath(dir);
        const assets = new Set();
        const hash = createHash('sha256');
        for (const page of SHELL) {
          const file = path.join(out, page, 'index.html');
          if (!existsSync(file)) throw new Error(`pwa: shell page ${page || '(root)'} was not built`);
          const html = readFileSync(file, 'utf8');
          hash.update(html);
          for (const m of html.matchAll(/["'(]((?:\/[^"'()\s]*)?\/_astro\/[^"'()\s]+)["')]/g)) assets.add(m[1]);
        }
        for (const s of STATIC) hash.update(readFileSync(path.join(out, s)));
        const shell = [...SHELL.map((p) => base + p), ...STATIC.map((s) => base + s)];
        const files = [...assets].sort();
        const version = hash.digest('hex').slice(0, 12);
        writeFileSync(path.join(out, 'sw.js'), sw(version, base, shell, files));
        // The list behind "Save all pages for offline reading" (garden page): every
        // page of each language, the scripts and fonts they use, and their sizes.
        const all = { version, langs: {}, assets: [], assetBytes: 0 };
        const used = new Set();
        for (const lang of ['tr', 'en']) {
          const pages = [];
          let bytes = 0;
          const walk = (dir) => {
            for (const name of readdirSync(dir)) {
              const p = path.join(dir, name);
              if (statSync(p).isDirectory()) walk(p);
              else if (name === 'index.html') {
                const html = readFileSync(p, 'utf8');
                bytes += Buffer.byteLength(html);
                pages.push(base + path.relative(out, path.dirname(p)).split(path.sep).join('/') + '/');
                for (const m of html.matchAll(/["'(]((?:\/[^"'()\s]*)?\/_astro\/[^"'()\s]+)["')]/g)) used.add(m[1]);
              }
            }
          };
          walk(path.join(out, lang));
          all.langs[lang] = { pages: pages.sort(), bytes };
        }
        all.assets = [...used].sort();
        all.assetBytes = all.assets.reduce((n, a) => {
          const f = path.join(out, a.slice(base.length));
          return n + (existsSync(f) ? statSync(f).size : 0);
        }, 0);
        writeFileSync(path.join(out, 'offline-manifest.json'), JSON.stringify(all));
        console.log(`pwa: sw.js (${version}), ${shell.length} pages and ${files.length} assets precached`);
      },
    },
  };
}

const sw = (version, base, shell, files) => `// Generated by integrations/pwa.mjs at build time. Do not edit.
const SHELL = 'tefekkur-shell-${version}';
const PAGES = 'tefekkur-pages';
const ASSETS = 'tefekkur-assets';
const BASE = ${JSON.stringify(base)};
const SHELL_FILES = ${JSON.stringify(shell, null, 1)};
const ASSET_FILES = ${JSON.stringify(files, null, 1)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    Promise.all([
      caches.open(SHELL).then((c) => c.addAll(SHELL_FILES)),
      caches.open(ASSETS).then((c) => c.addAll(ASSET_FILES)),
    ]).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('tefekkur-shell-') && k !== SHELL).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin || !url.pathname.startsWith(BASE)) return;

  // Saving a copy is wrapped in event.waitUntil: without it, iOS Safari may stop the
  // worker before the copy is written, and the page is never available offline.
  const keep = (cache, res) => {
    if (res.ok && !res.redirected) {
      const copy = res.clone();
      event.waitUntil(caches.open(cache).then((c) => c.put(req, copy)));
    }
    return res;
  };
  // Never answer with nothing: Safari treats an empty answer as an error.
  const orError = (hit) => hit || Response.error();

  if (req.mode === 'navigate') {
    // Pages: the latest when online; the saved copy, or the offline page, when not.
    event.respondWith(
      fetch(req)
        .then((res) => keep(PAGES, res))
        .catch(() =>
          caches
            .match(req, { ignoreSearch: true })
            .then((hit) => hit || caches.match(BASE + 'offline/'))
            .then(orError),
        ),
    );
    return;
  }

  // Icons, the manifest and other unhashed files: fresh when online, saved copy offline.
  if (!url.pathname.startsWith(BASE + '_astro/')) {
    event.respondWith(fetch(req).catch(() => caches.match(req).then(orError)));
    return;
  }

  // Scripts and fonts in _astro/: their names change when their content does.
  event.respondWith(
    caches.match(req).then((hit) => hit || fetch(req).then((res) => keep(ASSETS, res))),
  );
});
`;
